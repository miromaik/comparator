import { copyToClipboard, showToast, debounce } from '../../utils/helpers'

interface ServerProps {
  'server-port': number
  'server-ip': string
  'gamemode': 'survival' | 'creative' | 'adventure' | 'spectator'
  'difficulty': 'peaceful' | 'easy' | 'normal' | 'hard'
  'pvp': boolean
  'hardcore': boolean
  'online-mode': boolean
  'white-list': boolean
  'allow-flight': boolean
  'spawn-monsters': boolean
  'spawn-animals': boolean
  'spawn-npcs': boolean
  'view-distance': number
  'simulation-distance': number
  'max-players': number
  'level-seed': string
  'motd': string
  'enable-rcon': boolean
  'rcon.port': number
  'rcon.password': string
}

const DEFAULT_PROPS: ServerProps = {
  'server-port': 25565,
  'server-ip': '',
  'gamemode': 'survival',
  'difficulty': 'easy',
  'pvp': true,
  'hardcore': false,
  'online-mode': true,
  'white-list': false,
  'allow-flight': false,
  'spawn-monsters': true,
  'spawn-animals': true,
  'spawn-npcs': true,
  'view-distance': 10,
  'simulation-distance': 10,
  'max-players': 20,
  'level-seed': '',
  'motd': 'A Minecraft Server',
  'enable-rcon': false,
  'rcon.port': 25575,
  'rcon.password': '',
}

const props: ServerProps = { ...DEFAULT_PROPS }

export function mount(container: HTMLElement): void {
  function generateFile(): string {
    const lines = [
      '# Minecraft server properties',
      '# Generated by Comparator Toolbox',
      `# Date: ${new Date().toISOString().split('T')[0]}`,
    ]

    for (const [k, v] of Object.entries(props)) {
      lines.push(`${k}=${v}`)
    }

    return lines.join('\n')
  }

  function update(): void {
    const outEl = document.getElementById('sp-output')
    if (outEl) outEl.textContent = generateFile()
  }

  const debouncedUpdate = debounce(update, 40)

  container.innerHTML = `
    <div class="split-view">
      <!-- Controls -->
      <div class="panel">
        <div class="panel-header">
          <span class="panel-title">Server Settings</span>
          <button class="btn btn-sm" id="sp-reset">Reset Defaults</button>
        </div>
        <div class="panel-body">
          <!-- Gameplay Settings -->
          <div class="form-group">
            <label class="form-label">Gamemode & Difficulty</label>
            <div class="form-row-2">
              <select id="sp-gamemode" class="select">
                <option value="survival" ${props.gamemode === 'survival' ? 'selected' : ''}>Survival</option>
                <option value="creative" ${props.gamemode === 'creative' ? 'selected' : ''}>Creative</option>
                <option value="adventure" ${props.gamemode === 'adventure' ? 'selected' : ''}>Adventure</option>
                <option value="spectator" ${props.gamemode === 'spectator' ? 'selected' : ''}>Spectator</option>
              </select>
              <select id="sp-difficulty" class="select">
                <option value="peaceful" ${props.difficulty === 'peaceful' ? 'selected' : ''}>Peaceful</option>
                <option value="easy" ${props.difficulty === 'easy' ? 'selected' : ''}>Easy</option>
                <option value="normal" ${props.difficulty === 'normal' ? 'selected' : ''}>Normal</option>
                <option value="hard" ${props.difficulty === 'hard' ? 'selected' : ''}>Hard</option>
              </select>
            </div>
          </div>

          <!-- Gameplay Toggles -->
          <div class="form-group">
            <label class="form-label">Rules & Spawns</label>
            <div class="btn-grid-3">
              <button class="toggle-btn ${props.pvp ? 'active' : ''}" data-prop-toggle="pvp">PvP Enabled</button>
              <button class="toggle-btn ${props.hardcore ? 'active' : ''}" data-prop-toggle="hardcore">Hardcore</button>
              <button class="toggle-btn ${props['allow-flight'] ? 'active' : ''}" data-prop-toggle="allow-flight">Allow Flight</button>
              <button class="toggle-btn ${props['spawn-monsters'] ? 'active' : ''}" data-prop-toggle="spawn-monsters">Spawn Monsters</button>
              <button class="toggle-btn ${props['spawn-animals'] ? 'active' : ''}" data-prop-toggle="spawn-animals">Spawn Animals</button>
              <button class="toggle-btn ${props['spawn-npcs'] ? 'active' : ''}" data-prop-toggle="spawn-npcs">Spawn Villagers</button>
            </div>
          </div>

          <!-- Network & Security -->
          <div class="form-group">
            <label class="form-label">Network & Security</label>
            <div class="btn-grid-2">
              <button class="toggle-btn ${props['online-mode'] ? 'active' : ''}" data-prop-toggle="online-mode">
                Online Mode (Mojang Auth)
              </button>
              <button class="toggle-btn ${props['white-list'] ? 'active' : ''}" data-prop-toggle="white-list">
                Whitelist Enabled
              </button>
            </div>
          </div>

          <!-- Performance & Limits -->
          <div class="form-row-3">
            <div class="form-group">
              <label class="form-label" for="sp-port">Server Port</label>
              <input id="sp-port" class="input" type="number" value="${props['server-port']}" />
            </div>
            <div class="form-group">
              <label class="form-label" for="sp-max-players">Max Players</label>
              <input id="sp-max-players" class="input" type="number" value="${props['max-players']}" min="1" />
            </div>
            <div class="form-group">
              <label class="form-label" for="sp-view-dist">View Dist</label>
              <input id="sp-view-dist" class="input" type="number" value="${props['view-distance']}" min="2" max="32" />
            </div>
          </div>

          <!-- World Seed -->
          <div class="form-group">
            <label class="form-label" for="sp-seed">World Seed (leave empty for random)</label>
            <input id="sp-seed" class="input" type="text" value="${props['level-seed']}" placeholder="e.g. 482910482048102" />
          </div>
        </div>
      </div>

      <!-- Properties File Output -->
      <div class="panel">
        <div class="panel-header">
          <span class="panel-title">Generated server.properties</span>
        </div>
        <div class="panel-body">
          <div class="output-block">
            <div class="output-header">
              <span class="output-label">server.properties</span>
              <div class="output-actions">
                <button class="btn btn-sm" id="sp-download">Download</button>
                <button class="btn btn-copy" id="sp-copy">Copy</button>
              </div>
            </div>
            <div class="output-code" id="sp-output" style="max-height: 380px;"></div>
          </div>
        </div>
      </div>
    </div>
  `

  document.getElementById('sp-gamemode')?.addEventListener('change', (e) => {
    props.gamemode = (e.target as HTMLSelectElement).value as ServerProps['gamemode']
    update()
  })

  document.getElementById('sp-difficulty')?.addEventListener('change', (e) => {
    props.difficulty = (e.target as HTMLSelectElement).value as ServerProps['difficulty']
    update()
  })

  container.querySelectorAll<HTMLButtonElement>('[data-prop-toggle]').forEach(btn => {
    btn.addEventListener('click', () => {
      const key = btn.dataset.propToggle as keyof ServerProps
      ;(props as any)[key] = !(props as any)[key]
      btn.classList.toggle('active', Boolean(props[key]))
      update()
    })
  })

  const portInput = document.getElementById('sp-port') as HTMLInputElement
  const maxPlayersInput = document.getElementById('sp-max-players') as HTMLInputElement
  const viewDistInput = document.getElementById('sp-view-dist') as HTMLInputElement
  const seedInput = document.getElementById('sp-seed') as HTMLInputElement

  portInput?.addEventListener('input', () => {
    props['server-port'] = parseInt(portInput.value, 10) || 25565
    debouncedUpdate()
  })

  maxPlayersInput?.addEventListener('input', () => {
    props['max-players'] = parseInt(maxPlayersInput.value, 10) || 20
    debouncedUpdate()
  })

  viewDistInput?.addEventListener('input', () => {
    props['view-distance'] = parseInt(viewDistInput.value, 10) || 10
    props['simulation-distance'] = props['view-distance']
    debouncedUpdate()
  })

  seedInput?.addEventListener('input', () => {
    props['level-seed'] = seedInput.value
    debouncedUpdate()
  })

  document.getElementById('sp-reset')?.addEventListener('click', () => {
    Object.assign(props, DEFAULT_PROPS)
    mount(container)
    showToast('Reset to vanilla defaults!')
  })

  document.getElementById('sp-copy')?.addEventListener('click', async () => {
    const text = generateFile()
    await copyToClipboard(text)
    showToast('server.properties copied!')
  })

  document.getElementById('sp-download')?.addEventListener('click', () => {
    const text = generateFile()
    const blob = new Blob([text], { type: 'text/plain' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = 'server.properties'
    a.click()
    URL.revokeObjectURL(url)
    showToast('server.properties downloaded!')
  })

  update()
}
